#!/usr/bin/env python3
"""Package extension/ into dist/codes-<version>.xpi (reproducible zip).

usage: tools/build.py [--id codes@yourdomain.com] [--server https://codes.yourdomain.com]

  --id      add-on ID written into the manifest. Needed to sign, and must be unique on addons.mozilla.org.
  --server  server address baked in as the default, so the extension only asks for the access key.

Both can also be set as CODES_EXTENSION_ID and CODES_SERVER, in the environment or in the repository's .env.
Without CODES_SERVER, https://$CODES_DOMAIN is used when .env defines it.
"""
import argparse, json, os, re, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT, DIST = os.path.join(ROOT, "extension"), os.path.join(ROOT, "dist")
PLACEHOLDER_ID = "codes@example.com"


def dotenv():
    path, out = os.path.join(ROOT, ".env"), {}
    if os.path.isfile(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip().strip("\"'")
    return out


def setting(key, default=""):
    return os.environ.get(key) or dotenv().get(key) or default


def default_server():
    domain = setting("CODES_DOMAIN")
    return setting("CODES_SERVER") or (f"https://{domain}" if domain else "")


def build(ext_id=None, server=None):
    ext_id = ext_id or setting("CODES_EXTENSION_ID") or PLACEHOLDER_ID
    server = (server if server is not None else default_server()).rstrip("/")
    if server and not re.fullmatch(r"https://[A-Za-z0-9.-]+(:\d+)?", server):
        sys.exit(f"--server must look like https://codes.example.com (got {server!r})")
    if not re.fullmatch(r"[A-Za-z0-9._+-]+@[A-Za-z0-9.-]+|\{[0-9a-fA-F-]{36}\}", ext_id):
        sys.exit(f"--id must look like name@domain (got {ext_id!r})")
    manifest = json.load(open(os.path.join(EXT, "manifest.json"), encoding="utf-8"))
    manifest["browser_specific_settings"]["gecko"]["id"] = ext_id
    version = manifest["version"]
    os.makedirs(DIST, exist_ok=True)
    out = os.path.join(DIST, f"codes-{version}.xpi")
    overrides = {
        "manifest.json": json.dumps(manifest, indent=2, ensure_ascii=False).encode() + b"\n",
        "config.js": f"// Generated by tools/build.py\nconst DEFAULT_SERVER = {json.dumps(server)};\n".encode(),
    }
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for d, dirs, files in sorted(os.walk(EXT)):
            dirs.sort()
            for f in sorted(files):
                path = os.path.join(d, f)
                name = os.path.relpath(path, EXT).replace(os.sep, "/")
                info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, overrides.get(name) or open(path, "rb").read())
    return out, version, ext_id


if __name__ == "__main__":
    p = argparse.ArgumentParser(description="Package the Firefox extension.")
    p.add_argument("--id", help="add-on ID, e.g. codes@yourdomain.com")
    p.add_argument("--server", help="default server address, e.g. https://codes.yourdomain.com")
    a = p.parse_args()
    out, version, ext_id = build(a.id, a.server)
    server = (default_server() if a.server is None else a.server).rstrip("/")
    print(f"{out}  (version {version}, id {ext_id}, server {server or 'none'})")
